export function getCategory(slug) { return categories.find((item) => item.slug === slug); }
export function getArticle(slug) { return articles.find((item) => item.slug === slug); }
export function getArticlesByCategory(slug) { return articles.filter((item) => item.category === slug); }
export function categoryName(slug) { return getCategory(slug)?.label ?? 'راهنمای مایکا'; }
export function searchArticles(query) {
  const q = query.trim().toLocaleLowerCase('fa');
  if (!q) return [];
  return articles.filter((article) =>
    [article.title, article.excerpt, categoryName(article.category), ...article.paragraphs].join(' ').toLocaleLowerCase('fa').includes(q)
  );
}
